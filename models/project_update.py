from odoo import _, fields, models
from odoo.exceptions import UserError

from .project_project import INTERNAL


class ProjectUpdate(models.Model):
    _inherit = "project.update"

    handover_id = fields.Many2one(
        "urbana.sku.handover", string="Handover", copy=False, readonly=True, ondelete="set null"
    )

    def write(self, vals):
        if self.filtered("handover_id") and not self.env.context.get(INTERNAL):
            raise UserError(_("Updates generated by a handover cannot be edited."))
        return super().write(vals)

    def unlink(self):
        if self.filtered("handover_id") and not self.env.context.get(INTERNAL):
            raise UserError(_("Updates generated by a handover cannot be deleted."))
        return super().unlink()
